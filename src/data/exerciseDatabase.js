// Grouped by muscle for picker UIs
export const EXERCISES_BY_MUSCLE = EXERCISE_DATABASE.reduce((acc, ex) => {
  if (!acc[ex.muscle]) acc[ex.muscle] = [];
  acc[ex.muscle].push(ex);
  return acc;
}, {});

// Grouped by equipment
export const EXERCISES_BY_EQUIPMENT = EXERCISE_DATABASE.reduce((acc, ex) => {
  if (!acc[ex.equipment]) acc[ex.equipment] = [];
  acc[ex.equipment].push(ex);
  return acc;
}, {});

export const MUSCLE_GROUPS = [...new Set(EXERCISE_DATABASE.map(e => e.muscle))].sort();
export const EQUIPMENT_TYPES = [...new Set(EXERCISE_DATABASE.map(e => e.equipment))].sort();

export function searchExercises(query = '', filters = {}) {
  const q = query.toLowerCase();
  return EXERCISE_DATABASE.filter(ex => {
    const matchesQuery = !q || ex.name.toLowerCase().includes(q) ||
      ex.muscle.toLowerCase().includes(q) ||
      (ex.secondary || []).some(s => s.toLowerCase().includes(q));
    const matchesMuscle = !filters.muscle || ex.muscle === filters.muscle;
    const matchesEquipment = !filters.equipment || ex.equipment === filters.equipment;
    const matchesDifficulty = !filters.difficulty || ex.difficulty === filters.difficulty;
    return matchesQuery && matchesMuscle && matchesEquipment && matchesDifficulty;
  });
}

export function getFormRule(exerciseName) {
  const ex = EXERCISE_DATABASE.find(e => e.name.toLowerCase() === exerciseName.toLowerCase());
  return ex?.formRule || 'guided';
}

export function hasAIFormDetection(exerciseName) {
  return getFormRule(exerciseName) !== 'guided';
}
